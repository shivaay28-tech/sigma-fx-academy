function q(id: string, prompt: string, options: [string, string, string, string], correctIndex: 0 | 1 | 2 | 3, explanation: string) {
  const letters = ['a', 'b', 'c', 'd'] as const
  return {
    id,
    prompt,
    options: options.map((text, index) => ({ id: `${id}-${letters[index] ?? 'a'}`, text })),
    correctOptionId: `${id}-${letters[correctIndex] ?? 'a'}`,
    explanation,
  }
}

function quiz(n: string, title: string, questions: ReturnType<typeof q>[]): Quiz {
  return { id: `quiz-x${n}`, courseId: `course-x${n}`, title: `${title} — knowledge check`, passingScore: PASSING_SCORE, questions }
}

