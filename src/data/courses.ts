function lesson(
  id: string,
  slug: string,
  title: string,
  durationMinutes: number,
  order: number,
  summary: string,
  content: string[],
  resourceName = 'Lesson notes (PDF)',
): Lesson {
  return { id, slug, title, durationMinutes, order, summary, content, resourceName }
}

function module(id: string, title: string, order: number, lessons: Lesson[]): Module {
  return { id, title, order, lessons }
}

